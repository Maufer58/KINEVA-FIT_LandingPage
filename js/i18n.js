window.siteI18n = {
  lang: localStorage.getItem('stride-site-lang') || localStorage.getItem('move-site-lang') || 'it',
  translations,

  apply(lang) {
    this.lang = lang;
    localStorage.setItem('stride-site-lang', lang);
    document.documentElement.lang = lang;
    const dict = translations[lang] || translations.it;
    document.querySelectorAll('[data-i18n]').forEach((el) => {
      const key = el.getAttribute('data-i18n');
      if (dict[key]) el.textContent = dict[key];
    });
    const toggle = document.getElementById('langToggle');
    if (toggle) toggle.textContent = lang === 'it' ? 'EN' : 'IT';
  },

  toggle() {
    this.apply(this.lang === 'it' ? 'en' : 'it');
  },
};

document.addEventListener('DOMContentLoaded', () => {
  window.siteI18n.apply(window.siteI18n.lang);
});
